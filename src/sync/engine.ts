import { DatabaseRepository } from '../database/repository.js';
import { TraktClient } from '../trakt/client.js';
import { WatchStateEvent } from '@aiostreams/addon-sdk';

export class SyncEngine {
  constructor(private db: DatabaseRepository, private traktClient: TraktClient) {}

  async processEvent(userId: string, event: WatchStateEvent) {
    const { event: eventType, metaId, videoId, at } = event;
    
    // 1. Idempotency Check
    const existingEvent = await this.db.getSyncEvent(event.id);
    if (existingEvent && existingEvent.status === 'processed') {
      console.log(`Event ${event.id} already processed. Skipping.`);
      return;
    }

    // 2. Echo Protection
    // Ignore events that were generated by the system (sync engine)
    if (existingEvent && existingEvent.source === 'system') {
      console.log(`Event ${event.id} is a system-generated echo. Skipping.`);
      return;
    }

    // 3. Resolve media item
    let mediaItem = await this.db.getMediaItem(videoId);
    if (!mediaItem) {
      mediaItem = await this.db.upsertMediaItem({
        id: videoId,
        mediaType: event.scope === 'movie' ? 'movie' : 'series',
        canonicalMetaId: metaId,
        createdAt: new Date(),
        updatedAt: new Date(),
      })[0];
    }

    // 4. Conflict Resolution (Latest Action Wins)
    const currentState = await this.db.getPlaybackState(userId, mediaItem.id);
    if (currentState) {
      const newTimestamp = new Date(at).getTime();
      const currentTimestamp = new Date(currentState.sourceTimestamp).getTime();

      if (newTimestamp < currentTimestamp) {
        console.log(`Conflict detected: event is older than current state. Skipping.`);
        await this.db.upsertSyncEvent({
          id: event.id,
          userId,
          mediaItemId: mediaItem.id,
          eventType,
          source: 'jellyfin',
          eventTimestamp: new Date(at),
          status: 'skipped',
          createdAt: new Date(),
        });
        return;
      }

      if (newTimestamp === currentTimestamp && currentState.source === 'jellyfin') {
        console.log(`Conflict detected: event timestamp equals current state (Jellyfin priority). Skipping.`);
        return;
      }
    }

    // 5. Apply event to Trakt
    try {
      const type = event.scope === 'movie' ? 'movie' : 'episode';
      
      switch (eventType) {
        case 'start':
        case 'pause':
        case 'stop':
          await this.traktClient.scrobble(videoId, (event.positionMs / event.durationMs) * 100, event.durationMs);
          break;
        case 'played':
          await this.traktClient.markWatched(videoId, type, event.season, event.episode);
          break;
        case 'unplayed':
          await this.traktClient.markUnwatched(videoId, type, event.season, event.episode);
          break;
        case 'watchlisted':
          await this.traktClient.updateWatchlist(videoId, event.scope === 'movie' ? 'movie' : 'show', 'add');
          break;
        case 'unwatchlisted':
          await this.traktClient.updateWatchlist(videoId, event.scope === 'movie' ? 'movie' : 'show', 'remove');
          break;
        case 'rated':
          await this.traktClient.updateRating(videoId, event.scope === 'movie' ? 'movie' : (event.season ? 'season' : 'episode'), event.rating, event.season, event.episode);
          break;
        case 'unrated':
          await this.traktClient.updateRating(videoId, event.scope === 'movie' ? 'movie' : (event.season ? 'season' : 'episode'), null, event.season, event.episode);
          break;
      }

      // 6. Update local state
      await this.db.upsertPlaybackState({
        id: `${userId}:${videoId}`,
        userId,
        mediaItemId: mediaItem.id,
        videoId,
        season: event.season,
        episode: event.episode,
        positionMs: event.positionMs ?? 0,
        durationMs: event.durationMs ?? 0,
        progressPercent: event.durationMs ? (event.positionMs / event.durationMs) * 100 : 0,
        watched: eventType === 'played',
        source: 'jellyfin',
        sourceTimestamp: new Date(at),
        updatedAt: new Date(),
      });

      await this.db.upsertSyncEvent({
        id: event.id,
        userId,
        mediaItemId: mediaItem.id,
        eventType,
        source: 'jellyfin',
        eventTimestamp: new Date(at),
        status: 'processed',
        createdAt: new Date(),
      });

    } catch (error) {
      console.error(`Failed to sync event ${eventType} for ${videoId}:`, error);
      await this.db.upsertSyncEvent({
        id: event.id,
        userId,
        mediaItemId: mediaItem.id,
        eventType,
        source: 'jellyfin',
        eventTimestamp: new Date(at),
        status: 'failed',
        lastError: error instanceof Error ? error.message : String(error),
        createdAt: new Date(),
      });
      throw error;
    }
  }

  async getWatchedVersion(userId: string): Promise<string> {
    const syncState = await this.db.getSyncState(userId);
    if (!syncState) return 'v0';

    const lastEvent = await this.db.getLatestSyncEvent(userId);
    const eventTimestamp = lastEvent ? lastEvent.eventTimestamp.getTime() : 0;
    const traktTimestamp = syncState.lastTraktActivity.getTime();

    // Version is a hash of the last processed event and last Trakt activity
    return `v${eventTimestamp}-${traktTimestamp}`;
  }

  async syncFromTrakt(userId: string) {

    const history = await this.traktClient.getSyncHistory();
    const activities = await this.traktClient.getActivities();
    
    // 1. Update local sync state with latest Trakt activity
    const latestActivity = activities.length > 0 
      ? new Date(activities[0].timestamp) 
      : new Date();
      
    await this.db.upsertSyncState({
      id: `sync-state:${userId}`,
      userId,
      watchedVersion: `v${Date.now()}`,
      lastTraktActivity: latestActivity,
      lastFullSync: new Date(),
      lastIncrementalSync: new Date(),
      updatedAt: new Date(),
    });

    // 2. Process history and update local playback state
    for (const item of history.items) {
      const mediaItem = await this.db.getMediaItem(item.videoId) || await this.db.upsertMediaItem({
        id: item.videoId,
        mediaType: item.type,
        canonicalMetaId: item.metaId,
        createdAt: new Date(),
        updatedAt: new Date(),
      });

      const currentState = await this.db.getPlaybackState(userId, mediaItem.id);
      const traktTimestamp = new Date(item.timestamp);

      if (currentState && new Date(currentState.sourceTimestamp) > traktTimestamp) {
        console.log(`Conflict detected: Trakt state for ${item.videoId} is older than local state. Skipping.`);
        continue;
      }

      await this.db.upsertPlaybackState({
        id: `${userId}:${mediaItem.id}`,
        userId,
        mediaItemId: mediaItem.id,
        videoId: item.videoId,
        season: item.season,
        episode: item.episode,
        positionMs: item.positionMs || 0,
        durationMs: item.durationMs || 0,
        progressPercent: item.progressPercent || 0,
        watched: item.watched,
        source: 'trakt',
        sourceTimestamp: traktTimestamp,
        updatedAt: new Date(),
      });
    }
  }
}
